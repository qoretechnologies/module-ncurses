import argparse
import json
import os
from pathlib import Path
import re
import subprocess

ROOT = Path(__file__).resolve().parents[1]
STATES = ('default', 'empty', 'focused', 'selected', 'disabled', 'invalid', 'loading', 'unicode', 'constrained')
BASES = {'Widget', 'PanelWidget', 'ScrollableWidget'}


def load(build):
    env = dict(os.environ, QORE_MODULE_DIR=f'{Path(build).resolve()}:{ROOT / "qlib"}')
    result = subprocess.run(['qore', '--enable-debug', '--warnings-are-errors', 'examples/widget-gallery.qr', '--catalog'],
                            cwd=ROOT, env=env, text=True, capture_output=True, check=True)
    if result.stderr:
        raise ValueError(result.stderr)
    return json.loads(result.stdout)


def validate(stories, public=None):
    if public is None:
        public = set()
        for source in (ROOT / 'qlib/NcursesUi').glob('*.qc'):
            public.update(re.findall(r'^public class (\w*Widget)\b', source.read_text(), re.M))
        public -= BASES
    ids = {story['id'] for story in stories}
    if len(ids) != len(stories):
        raise ValueError('Duplicate story IDs')
    registered = {story['widget'] for story in stories}
    if public != registered:
        raise ValueError(f'Widget inventory mismatch: missing={sorted(public-registered)}, unexpected={sorted(registered-public)}')
    for story in stories:
        if not re.fullmatch(r'[a-z0-9-]+\.[a-z0-9-]+', story['id']):
            raise ValueError(f'Invalid stable ID: {story["id"]}')
        for field in ('purpose', 'api', 'api_url', 'keyboard', 'mouse', 'fixture', 'steps'):
            if not story.get(field):
                raise ValueError(f'{story["id"]}: missing {field}')
        if set(story['states']) != set(STATES):
            raise ValueError(f'{story["id"]}: incomplete state matrix')
        for state, disposition in story['states'].items():
            if disposition.startswith('N/A: '):
                if len(disposition) < 20:
                    raise ValueError(f'{story["id"]}: explain why {state} is not applicable')
            elif disposition not in ids:
                raise ValueError(f'{story["id"]}: unregistered {state} scenario {disposition}')
        checkpoints = [step['checkpoint'] for step in story['steps']]
        if len(checkpoints) != len(set(checkpoints)) or not all(checkpoints):
            raise ValueError(f'{story["id"]}: duplicate or empty checkpoints')
        if any(story['geometry'][axis] < 1 for axis in ('rows', 'cols')):
            raise ValueError(f'{story["id"]}: invalid geometry')
    mouse_widgets = {story['widget'] for story in stories if story['state'] == 'mouse'}
    expected_mouse = registered - {'LabelWidget', 'StatusBarWidget'}
    if mouse_widgets != expected_mouse:
        raise ValueError(f'Missing mouse scenarios: {sorted(expected_mouse - mouse_widgets)}')


def render(stories):
    validate(stories)
    lines = ['/* Copyright 2026 Qore Technologies, s.r.o. */',
             '/* Generated by tools/widget_catalog.py; edit examples/gallery/ instead. */',
             '/** @page ncurses_widget_catalog Widget Story Catalog', '',
             'One executable registry supplies this catalog, the native gallery and deterministic tests.',
             'Run from the checkout root:', '@verbatim',
             'QORE_MODULE_DIR=build-debug:qlib qore --enable-debug --warnings-are-errors examples/widget-gallery.qr',
             'QORE_MODULE_DIR=build-debug:qlib qore --enable-debug --warnings-are-errors examples/widget-gallery.qr --headless --story table.scrolling',
             '@endverbatim', '',
             'F1 opens contextual help, F2 searches stories, F3 resets the fixture, F4 cycles viewport presets,',
             'F5 executes the next documented step, F6 inspects focus/scroll/cursor, and Ctrl+Q exits.',
             'Presets change ncurses logical viewport dimensions, not the physical terminal device.',
             'The headless runner starts at the registered geometry and checks every completed draw.',
             'Use @ref ncursestestingcapture for the capture contract and limitations.', '',
             '@section catalog_shared Shared Infrastructure',
             '@ref NcursesUi::Widget "Widget" supplies tree geometry, focus availability, input and dirty drawing.',
             '@ref NcursesUi::PanelWidget "PanelWidget" supplies clipped stacking and native-resource lifetime.',
             '@ref NcursesUi::ScrollableWidget "ScrollableWidget" supplies viewport, scroll bounds and cursor ownership.',
             'Editor/table/popup stories exercise their composition; dedicated layout, focus and capture suites cover boundaries.', '']
    for story in stories:
        if story['state'] != 'default':
            continue
        lines += [f'@section catalog_{story["id"].replace(".", "_").replace("-", "_")} {story["widget"]}',
                  f'API: @ref {story["api"]} "{story["widget"]}". [Source]({story["api_url"]})', '', story['purpose'], '',
                  f'Keyboard: {story["keyboard"]}', f'Mouse: {story["mouse"]}', '',
                  '| State | Story or reason |', '| --- | --- |']
        lines += [f'| {state} | {story["states"][state]} |' for state in STATES]
        lines += ['', f'Initial geometry: {story["geometry"]["rows"]} rows × {story["geometry"]["cols"]} columns.',
                  'Checkpoints: ' + '; '.join(f'{step["checkpoint"]}: {step["instruction"]}' for step in story['steps']), '']
    lines += ['@section catalog_interactions Additional Interaction Scenarios',
              'Every interactive widget has a mouse story. Label and StatusBar are read-only and have no mouse action.',
              'These cases use the same native events for headless assertions and real PTY/browser input.', '',
              '| Story | Review checkpoint |', '| --- | --- |']
    lines += [f'| {story["id"]} | {story["purpose"]} |' for story in stories if story['state'] in ('mouse', 'scenario')]
    return '\n'.join(lines + ['', '*/', ''])


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--build-dir', default=str(ROOT / 'build-debug'))
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    text = render(load(args.build_dir))
    destination = ROOT / 'docs/widget-catalog.dox'
    if args.check:
        if not destination.exists() or destination.read_text() != text:
            raise SystemExit('Widget catalog is out of date; run python3 tools/widget_catalog.py')
    else:
        destination.write_text(text)


if __name__ == '__main__':
    main()
